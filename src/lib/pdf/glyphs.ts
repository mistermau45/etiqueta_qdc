/** Desenha o ícone centrado em (cx, cy) com a caixa informada em pontos. */
export function desenharIcone(
  page: PDFPage,
  nome: string,
  cx: number,
  cy: number,
  tamanho: number,
  cor: RGB,
  espessura = 0.7,
): boolean {
  const segmentos = ICONES[nome] ?? ICONES.check
  if (!segmentos) return false

  const escala = tamanho / 24
  const deslocX = cx - (tamanho / 2)
  const deslocY = cy - tamanho / 2

  for (const [x1, y1, x2, y2] of segmentos) {
    const ax = deslocX + x1 * escala
    const ay = deslocY + (24 - y1) * escala
    const bx = deslocX + x2 * escala
    const by = deslocY + (24 - y2) * escala
    if (Math.abs(ax - bx) < 0.0001 && Math.abs(ay - by) < 0.0001) continue
    page.drawLine({ start: { x: ax, y: ay }, end: { x: bx, y: by }, thickness: espessura, color: cor })
  }
  return true
}

export function desenharIconeCentro(
  page: PDFPage,
  nome: string,
  cx: number,
  cy: number,
  tamanhoMm: number,
  cor: RGB,
): void {
  desenharIcone(page, nome, cx, cy, paraPt(tamanhoMm) * 1.02, cor, paraPt(0.45))
}

export function iconeDisponivel(nome: string): boolean {
  return nome in ICONES
}
